// #repository-tree.js: کنترل باز و بسته کردن درخت ثابت تولیدشده توسط GitHub Actions
"use strict";
(() => {
  const root = document.getElementById("treeRoot");
  const status = document.getElementById("treeStatus");
  const counts = document.getElementById("treeCounts");
  const refresh = document.getElementById("refreshTree");
  const expand = document.getElementById("expandAll");
  const collapse = document.getElementById("collapseAll");
  counts.textContent = root.querySelectorAll(".folder-node").length + " folders · " + root.querySelectorAll(".file-node").length + " files";
  status.textContent = "Static tree generated by GitHub Actions · branch main";
  root.querySelectorAll("details").forEach(details => details.addEventListener("toggle", () => {
    const marker = details.querySelector(":scope > summary .twisty");
    if (marker) marker.textContent = details.open ? "▾" : "▸";
  }));
  refresh.addEventListener("click", () => window.location.reload());
  expand.addEventListener("click", () => root.querySelectorAll("details").forEach(details => { details.open = true; }));
  collapse.addEventListener("click", () => root.querySelectorAll("details").forEach(details => { details.open = false; }));
})();
